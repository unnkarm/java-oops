public class Variable { //file name=class name
    public static void main(String[] args) {
        int a = 10; //variable declaration and initialization
        double b = 20.5; //variable declaration and initialization
        String c = "Hello"; //variable declaration and initialization
        long phoneNumber = 1234567890L; //variable declaration and initialization
        float d = 5.5f; //variable declaration and initialization
        boolean isJavaFun = true; //variable declaration and initialization

        System.out.println("Integer value: " + a);
        System.out.println("Double value: " + b);
        System.out.println("String value: " + c);
        System.out.println("Long value: " + phoneNumber);
        System.out.println("Float value: " + d);
        System.out.println("Boolean value: " + isJavaFun);
    }
}